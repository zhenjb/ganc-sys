func createDepositForTest(t *testing.T, server http.Handler, amount string) types.DepositResponse {
	t.Helper()

	req := types.DepositRequestBody{
		Owner:  "cosmos1alice",
		Denom:  "uusdc",
		Amount: amount,
	}

	rec := performRequest(t, server, http.MethodPost, "/api/deposit", req)
	if rec.Code != http.StatusOK {
		t.Fatalf("expected deposit status 200, got %d, body=%s", rec.Code, rec.Body.String())
	}

	return decodeJSON[types.DepositResponse](t, rec)
}

